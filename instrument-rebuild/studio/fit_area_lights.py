"""Fit small mathematical GGX -> LTC lookup tables (not image/scan data).
LTC model follows Heitz et al. 2016. This implementation fits a normalized
single-scatter isotropic GGX lobe with deterministic mixture quadrature.
It is an approximation; the emitted validation JSON records fitting errors.
"""
from pathlib import Path
import numpy as np, math, gzip,json,time
from scipy.optimize import least_squares
R=Path(__file__).resolve().parent.parent
N=32

def radical(n):
 a=np.arange(n,dtype=np.uint32);a=(a<<16)|(a>>16)
 a=((a&0x55555555)<<1)|((a&0xaaaaaaaa)>>1);a=((a&0x33333333)<<2)|((a&0xcccccccc)>>2)
 a=((a&0x0f0f0f0f)<<4)|((a&0xf0f0f0f0)>>4);a=((a&0x00ff00ff)<<8)|((a&0xff00ff00)>>8)
 return a.astype(float)*2.3283064365386963e-10

def normalize(p):return p/np.maximum(np.linalg.norm(p,axis=-1,keepdims=True),1e-20)
def target(L,V,alpha):
 H=normalize(L+V);nl=np.maximum(L[:,2],0);nv=V[2];nh=np.maximum(H[:,2],1e-8);vh=np.maximum(H@V,1e-8)
 D=alpha*alpha/(np.pi*(nh*nh*(alpha*alpha-1)+1)**2)
 lv=.5*(np.sqrt(1+alpha*alpha*(1-nv*nv)/(nv*nv))-1)
 ll=.5*(np.sqrt(1+alpha*alpha*(1-nl*nl)/np.maximum(nl*nl,1e-15))-1)
 F=D/(4*nv*(1+lv+ll));F=np.where(nl>0,F,0)
 pdf=D*nh/(4*vh)
 return F,pdf,(1-vh)**5

def sample_h(n,V,alpha):
 xi=(np.arange(n)+.5)/n;y=radical(n);ct=np.sqrt((1-y)/(1+(alpha*alpha-1)*y));st=np.sqrt(1-ct*ct);phi=2*np.pi*xi
 H=np.stack([st*np.cos(phi),st*np.sin(phi),ct],1);return 2*(H@V)[:,None]*H-V

def invmat(p):
 sx,sy=np.exp(p[:2]);sh=p[2];a=p[3];c,s=np.cos(a),np.sin(a)
 M=np.array([[c,0,s],[0,1,0],[-s,0,c]])@np.array([[sx,0,sh],[0,sy,0],[0,0,1]])
 return np.linalg.inv(M)

def pdf_model(L,p):
 I=invmat(p);q=L@I.T;l2=(q*q).sum(1)
 return np.maximum(q[:,2],0)*abs(np.linalg.det(I))/(np.pi*np.maximum(l2*l2,1e-30))

out=np.empty((2,N,N,4),'f2');params=np.zeros((N,N,4));loss=[];start=time.time()
# uniform halfsphere samples balance the importance lobe without missing tails
ni=512;nu=192;zz=(np.arange(nu)+.5)/nu;phi=np.arange(nu)*np.pi*(3-np.sqrt(5));rr=np.sqrt(1-zz*zz);U=np.stack([rr*np.cos(phi),rr*np.sin(phi),zz],1)
for y in range(N):
 nv=max(.035,1-(y/(N-1))**2);V=np.array([np.sqrt(1-nv*nv),0,nv])
 for x in range(N-1,-1,-1):
  rough=.10+.85*x/(N-1);alpha=rough*rough
  Lg=sample_h(ni,V,alpha);Lg=Lg[Lg[:,2]>0]
  L=np.r_[Lg,U];tar,pdfh,fc=target(L,V,alpha)
  normL=sample_h(4096,V,alpha);nf,npdf,nfc=target(normL,V,alpha)
  mag=max(1e-7,np.mean(nf/np.maximum(npdf,1e-20)));fmag=np.mean(nf*nfc/np.maximum(npdf,1e-20))
  mixpdf=(ni*pdfh+nu/(2*np.pi))/(ni+nu)
  weight=1/np.sqrt(np.maximum(mixpdf,1e-8)*len(L));tt=np.sqrt(tar/mag)
  theta=-np.arccos(nv);p0=np.array([np.log(max(alpha*1.55,.02)),np.log(max(alpha*1.55,.02)),0,theta])
  if x<N-1:p0=params[y,x+1].copy()
  elif y:p0=params[y-1,x].copy()
  def residual(p):return (np.sqrt(pdf_model(L,p)+1e-18)-tt)*weight
  fit=least_squares(residual,p0,bounds=([-6,-6,-8,-1.55],[2,2,8,.2]),max_nfev=28,ftol=5e-5,xtol=5e-5,gtol=5e-5)
  params[y,x]=fit.x;I=invmat(fit.x)
  # Remove uniform scale for a numerically stable half-float matrix.
  I/=max(np.linalg.norm(I),1e-8)
  out[0,y,x]=[I[0,0],I[0,2],I[1,1],I[2,0]]
  out[1,y,x]=[I[2,2],mag,fmag,0]
  loss.append(float(np.mean(residual(fit.x)**2)*len(L)))
 print('LTC row',y,'elapsed',round(time.time()-start,2),flush=True)
(R/'materials/area-lights.rgba16f.gz').write_bytes(gzip.compress(out.tobytes(),mtime=0))
(R/'materials/area-lights.json').write_text(json.dumps(dict(size=N,layers=2,format='RGBA16F',bytes=out.nbytes,source='Deterministic numerical fit of isotropic GGX to transformed cosine densities, generated by fit_area_lights.py; mathematical lookup data, not imagery.',roughnessRange=[.10,.95],viewCosineFloor=.035,fitSquaredHellingerMedian=float(np.median(loss)),fitSquaredHellingerP95=float(np.quantile(loss,.95)),elapsedSeconds=time.time()-start),indent=2))
